-- Run this once in Supabase Dashboard → SQL Editor.
-- In Authentication → Providers, enable Anonymous Sign-Ins before using the app.

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  full_name text not null,
  student_code text not null,
  email text not null,
  avatar_uri text,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (owner_id, student_code)
);

-- Upgrade a table created by the previous schema, if present.
alter table public.students add column if not exists owner_id uuid references auth.users(id) on delete cascade;
alter table public.students alter column owner_id set default auth.uid();
alter table public.students drop constraint if exists students_student_code_key;
alter table public.students drop constraint if exists students_owner_id_student_code_key;
alter table public.students add constraint students_owner_id_student_code_key unique (owner_id, student_code);

grant usage on schema public to authenticated;
grant select, insert, update, delete on table public.students to authenticated;
grant usage, select on sequence public.students_id_seq to authenticated;

alter table public.students enable row level security;

drop policy if exists "Students can select their own records" on public.students;
drop policy if exists "Students can insert their own records" on public.students;
drop policy if exists "Students can update their own records" on public.students;
drop policy if exists "Students can delete their own records" on public.students;

create policy "Students can select their own records"
on public.students for select to authenticated
using ((select auth.uid()) = owner_id);

create policy "Students can insert their own records"
on public.students for insert to authenticated
with check ((select auth.uid()) = owner_id);

create policy "Students can update their own records"
on public.students for update to authenticated
using ((select auth.uid()) = owner_id)
with check ((select auth.uid()) = owner_id);

create policy "Students can delete their own records"
on public.students for delete to authenticated
using ((select auth.uid()) = owner_id);
